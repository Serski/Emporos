// Builds samples/game-iso.html: the whole game as it is in src/game.html, with Rhodes drawn isometric by samples/iso-rhodes.js.
// It is a preview of an art style, not part of the game. Usage: node tools/build-iso-preview.mjs
import { readFileSync, writeFileSync } from 'node:fs';

const src = readFileSync(new URL('../src/game.html', import.meta.url), 'utf8');
const iso = readFileSync(new URL('../samples/iso-rhodes.js', import.meta.url), 'utf8');
// The game keeps all its code inside one closed scope, so the isometric Rhodes goes in just before that scope ends.
const close = src.lastIndexOf('})();', src.lastIndexOf('</script>'));
if (close < 0) throw new Error('src/game.html does not end its script with })();');
const game = src.slice(0, close) + '\n// ===== isometric Rhodes, from samples/iso-rhodes.js =====\n' + iso + '\n' + src.slice(close);
const end = game.indexOf('</style>');
if (end < 0) throw new Error('src/game.html has no <style> block to split on');
const cut = end + '</style>'.length;
const page = `<!doctype html>
<!-- Generated by tools/build-iso-preview.mjs from src/game.html and samples/iso-rhodes.js. A preview of an art style, not the game itself. -->
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">
<style>:root{padding-top:env(safe-area-inset-top,0px);padding-bottom:env(safe-area-inset-bottom,0px)}img{max-width:100%}</style>
${game.slice(0, cut).trim()}
</head>
<body>
${game.slice(cut).trim()}
</body>
</html>
`;
writeFileSync(new URL('../samples/game-iso.html', import.meta.url), page);
console.log(`Wrote samples/game-iso.html (${Math.round(page.length / 1024)} KB)`);
