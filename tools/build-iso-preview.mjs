// Builds a preview of an art style: the whole game as it is in src/game.html, with some scenes drawn by a script in samples/.
//   node tools/build-iso-preview.mjs                          samples/iso-style.js   -> samples/game-iso.html (isometric)
//   node tools/build-iso-preview.mjs flat-style game-2d       samples/flat-style.js  -> samples/game-2d.html  (the side view, eBoy fashion)
// It is a preview of an art style, not part of the game.
import { readFileSync, writeFileSync } from 'node:fs';

const style = process.argv[2] || 'iso-style', out = process.argv[3] || 'game-iso';
const src = readFileSync(new URL('../src/game.html', import.meta.url), 'utf8');
const code = readFileSync(new URL(`../samples/${style}.js`, import.meta.url), 'utf8');
// The game keeps all its code inside one closed scope, so the style's drawing goes in just before that scope ends.
const close = src.lastIndexOf('})();', src.lastIndexOf('</script>'));
if (close < 0) throw new Error('src/game.html does not end its script with })();');
const game = src.slice(0, close) + `\n// ===== drawing from samples/${style}.js =====\n` + code + '\n' + src.slice(close);
const end = game.indexOf('</style>');
if (end < 0) throw new Error('src/game.html has no <style> block to split on');
const cut = end + '</style>'.length;
const page = `<!doctype html>
<!-- Generated by tools/build-iso-preview.mjs from src/game.html and samples/${style}.js. A preview of an art style, not the game itself. -->
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">
<style>:root{padding-top:env(safe-area-inset-top,0px);padding-bottom:env(safe-area-inset-bottom,0px)}img{max-width:100%}</style>
${game.slice(0, cut).trim()}
</head>
<body>
${game.slice(cut).trim()}
</body>
</html>
`;
writeFileSync(new URL(`../samples/${out}.html`, import.meta.url), page);
console.log(`Wrote samples/${out}.html (${Math.round(page.length / 1024)} KB)`);
